package dev.chieppa.stretch.markdown

import androidx.compose.ui.text.SpanStyle
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertIs
import kotlin.test.assertTrue

/** Comments as bots write them on pull requests read into the blocks a [MarkdownView] shows. */
class BotCommentsTest {
    private val styles: RichStyles = { SpanStyle() }

    private fun tree(text: String) = viewTree(MarkdownDocument.parse(text).blocks, styles)

    private fun shown(node: ViewNode): String = when (node) {
        is ViewNode.Block -> readOnlyText(node.block.source, node.block.kind, styles).text.text
        is ViewNode.Inline -> readOnlyText(node.block.source, BlockKind.Paragraph, styles).text.text
        is ViewNode.Text -> node.text.text.text
        else -> error("no text in $node")
    }

    private fun kindOf(node: ViewNode) = assertIs<ViewNode.Block>(node).block.kind

    @Test
    fun readsASonarQualityGate() {
        val nodes = tree(sonarComment)
        assertEquals(BlockKind.Heading(2), kindOf(nodes[0]))
        val heading = readOnlyText(assertIs<ViewNode.Block>(nodes[0]).block.source, BlockKind.Heading(2), styles)
        assertEquals("Quality Gate failed", heading.text.text.trim())
        val badge = heading.pictures.single()
        assertTrue(badge.url.endsWith("qg-failed-20px.png"))
        assertEquals("https://sonarcloud.io/dashboard?id=acme_api&pullRequest=412", badge.link)
        assertEquals(listOf(0), heading.places, "the badge sits at the start of the heading's line")

        val conditions = readOnlyText(assertIs<ViewNode.Block>(nodes[1]).block.source, BlockKind.Paragraph, styles)
        val lines = conditions.text.text.lines().map { it.trim() }
        assertEquals(listOf("Failed conditions", "62.5% Coverage on New Code (required ≥ 80%)", "C Reliability Rating on New Code (required ≥ A)"), lines)
        assertEquals(2, conditions.pictures.size)
        assertEquals(lines[0].length + 3, conditions.places[0], "each icon sits at the start of its own line")

        assertEquals("See analysis details on SonarQube Cloud", shown(nodes[2]))
        assertEquals(ViewNode.Rule, nodes[3])
        assertEquals(5, nodes.size)
    }

    @Test
    fun readsAnOlderSonarCommentWithAnHtmlHeading() {
        val nodes = tree(sonarHtmlComment)
        val heading = assertIs<ViewNode.Text>(nodes[0])
        assertEquals(3, heading.heading)
        assertEquals("SonarCloud Quality Gate failed.", heading.text.text.text.trim())
        assertEquals(16, heading.text.pictures.single().width)
        val issues = readOnlyText(assertIs<ViewNode.Block>(nodes[1]).block.source, BlockKind.Paragraph, styles)
        assertEquals(listOf("Bug", "C", "Vulnerability"), issues.pictures.map { it.alt })
        assertEquals(listOf("1 Bug", "0 Vulnerabilities"), issues.text.text.lines().map { it.trim() })
        val details = assertIs<ViewNode.Details>(nodes[2])
        assertEquals(BlockKind.Heading(2), kindOf(details.children[0]))
        assertEquals(ListStyle.Task, assertIs<BlockKind.ListItem>(kindOf(details.children[1])).style)
        assertEquals(3, nodes.size)
    }

    @Test
    fun readsARenovateDescription() {
        val nodes = tree(renovateDescription)
        assertEquals(BlockKind.Table, kindOf(nodes[1]))
        val table = parseTable(assertIs<ViewNode.Block>(nodes[1]).block.source)
        val age = readOnlyText(table.rows[1][2], BlockKind.Paragraph, styles)
        assertEquals("", age.text.text.trim())
        assertEquals("https://docs.renovatebot.com/merge-confidence/", age.pictures.single().link)
        assertEquals("2.1.0 -> 2.1.20", readOnlyText(table.rows[1][1], BlockKind.Paragraph, styles).text.text)
        assertEquals(BlockKind.Heading(3), kindOf(nodes[3]))
        val notes = assertIs<ViewNode.Details>(nodes[4])
        assertEquals(listOf(BlockKind.Heading(3), BlockKind.Heading(4)), notes.children.take(2).map(::kindOf))
        assertEquals("📅 Schedule: Branch creation - At any time (no schedule defined).", shown(nodes[7]))
        assertEquals("If you want to rebase/retry this PR, check this box", shown(nodes[8]))
        assertEquals("This PR was generated by Mend Renovate.", shown(nodes.last()))
    }

    @Test
    fun aCommentOnTheFirstLineEndsWhereItCloses() {
        val nodes = tree(actionsComment)
        assertEquals("Benchmark results for 9c1e2fa", shown(nodes[0]))
        assertEquals(BlockKind.Heading(2), kindOf(nodes[1]))
        assertEquals(BlockKind.Table, kindOf(nodes[2]))
        assertEquals(BlockKind.Heading(4), kindOf(nodes[3]))
        assertIs<BlockKind.Code>(kindOf(nodes[4]))
        assertEquals("Posted by workflow run 1", shown(assertIs<ViewNode.Inline>(nodes[5])))
        assertEquals(6, nodes.size)
    }

    @Test
    fun readsACodecovReport() {
        val nodes = tree(codecovComment.replace("\n", "\r\n"))
        assertEquals("Codecov Report", shown(nodes[0]))
        assertEquals(BlockKind.Heading(2), kindOf(nodes[0]))
        assertEquals(BlockKind.Quote, kindOf(nodes[2]))
        assertEquals(BlockKind.Table, kindOf(nodes[3]))
        val details = assertIs<ViewNode.Details>(nodes[4])
        assertEquals("diff", assertIs<BlockKind.Code>(kindOf(details.children.single())).language)
        assertEquals("☂️ View full report in Codecov by Sentry.", shown(nodes[5]).lines().first().trim())
    }

    @Test
    fun anInlineTagCannotCutAParagraphShort() {
        val nodes = tree("First line\n<b>still</b> the same paragraph\n<div>\nblock\n</div>")
        assertEquals("First line\nstill the same paragraph", shown(nodes[0]))
        assertEquals(2, nodes.size)
    }

    @Test
    fun codeIsMarkedForItsFill() {
        val read = readOnlyText("Run `gradle build` or <code>make</code>", BlockKind.Paragraph, styles)
        val marked = read.text.getStringAnnotations(CODE_ANNOTATION, 0, read.text.length).map { read.text.text.substring(it.start, it.end) }
        assertEquals(setOf("gradle build", "make"), marked.toSet())
    }

    @Test
    fun shortcodesBecomeEmojiOutsideCode() {
        assertEquals("Ship it 🚀 :rocket: at 12:30:45", readOnlyText("Ship it :rocket: `:rocket:` at 12:30:45", BlockKind.Paragraph, styles).text.text)
    }

    @Test
    fun aPeekIsTheFirstLineAReaderSees() {
        assertEquals("Quality Gate failed", markdownPeek(sonarComment))
        assertEquals("Benchmark results for 9c1e2fa", markdownPeek(actionsComment))
        assertEquals("SonarCloud Quality Gate failed.", markdownPeek(sonarHtmlComment))
        assertEquals("Bumps actions/checkout from 3 to 4.", markdownPeek(dependabotDescription))
        assertEquals("", markdownPeek("<!-- nothing -->\n\n[//]: # (note)"))
    }
}
